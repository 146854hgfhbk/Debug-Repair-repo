import argparse
import json
import os
import re
import threading
from collections import Counter, defaultdict
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path


def normalize_code(code_string):
    if code_string is None:
        return ""
    code = re.sub(r"/\*.*?\*/", "", code_string, flags=re.DOTALL)
    code = re.sub(r"//.*", "", code)
    return re.sub(r"\s+", "", code).strip()


def add_bug_comments(code_string, buggy_line_numbers):
    lines = (code_string or "").split("\n")
    for line_num in buggy_line_numbers or []:
        if 1 <= line_num <= len(lines):
            lines[line_num - 1] = lines[line_num - 1].rstrip() + " // Buggy Line"
    return "\n".join(lines)


def build_patch_records(method, results):
    records = []
    for bug_id in sorted(results):
        result = results[bug_id]
        if result.get("status") != "success":
            continue
        for index, patch in enumerate(result.get("plausible_patches") or [], 1):
            if isinstance(patch, str) and patch.strip():
                records.append({
                    "method": method,
                    "bug_id": bug_id,
                    "patch_index": index,
                    "patch_id": f"{method}:{bug_id}:{index}",
                    "patch": patch,
                })
    return records


def classify_response(content):
    value = (content or "").strip()
    return value if value in {"Correct", "Incorrect"} else "Unknown"


def group_pending_by_bug(records, completed_entries):
    completed_ids = {entry["patch_id"] for entry in completed_entries}
    correct_bugs = {
        (entry["method"], entry["bug_id"])
        for entry in completed_entries
        if entry.get("judgment") == "Correct"
    }
    grouped = defaultdict(list)
    for record in records:
        key = (record["method"], record["bug_id"])
        if key not in correct_bugs and record["patch_id"] not in completed_ids:
            grouped[key].append(record)
    for pending in grouped.values():
        pending.sort(key=lambda record: record["patch_index"])
    return dict(grouped)


def construct_prompt(annotated_buggy_function, ground_truth_code, plausible_patch_code):
    return f"""You are an expert software engineer specializing in Automated Program Repair (APR). Your task is to determine if a plausible patch, generated by an APR tool, is semantically equivalent to the ground-truth developer patch.

A patch is considered "Correct" if it logically resolves the underlying bug in a manner equivalent to the ground-truth, even with minor variations in syntax, variable naming, or code style. It is "Incorrect" if it fails to fix the bug, introduces new bugs, or represents a fundamentally different and flawed logic.

First, here is the Original Buggy Function with the buggy lines marked by `// Buggy Line`:
{annotated_buggy_function}

Ground-truth Developer Patch:
{ground_truth_code}

Plausible Patch (Generated by APR tool):
{plausible_patch_code}

Is the plausible patch a correct fix? Your response must be exactly one word: Correct or Incorrect."""


def summarize_results(entries, expected_counts):
    summary = {}
    grouped = defaultdict(list)
    for entry in entries:
        grouped[entry["method"]].append(entry)
    for method, expected in expected_counts.items():
        method_entries = grouped[method]
        judgments = Counter(entry.get("judgment") for entry in method_entries)
        summary[method] = {
            "expected_patches": expected,
            "completed_patches": len(method_entries),
            "correct_patches": judgments["Correct"],
            "incorrect_patches": judgments["Incorrect"],
            "unknown": judgments["Unknown"],
            "errors": judgments["Error"],
            "correct_bugs": len({entry["bug_id"] for entry in method_entries if entry.get("judgment") == "Correct"}),
            "exact_matches": sum(bool(entry.get("exact_match")) for entry in method_entries),
        }
    return summary


def load_json(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def load_completed(path):
    entries = []
    if not os.path.exists(path):
        return entries
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                entries.append(json.loads(line))
    return entries


def ground_truth_context(ground_truth, bug_id):
    data = ground_truth.get(bug_id) or {}
    fix = data.get("fix")
    buggy = data.get("buggy")
    locations = data.get("location")
    start = data.get("start")
    if not fix or not buggy or locations is None or start is None:
        raise ValueError(f"ground truth fields missing for {bug_id}")
    relative = [absolute - start + 1 for absolute in locations]
    return fix, add_bug_comments(buggy, relative)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", action="append", required=True, metavar="METHOD=PATH")
    parser.add_argument("--ground-truth", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--summary", required=True)
    parser.add_argument("--model", default=os.getenv("VERIFY_MODEL", "grok-4.6"))
    parser.add_argument("--base-url", default=os.getenv("VERIFY_BASE_URL"))
    parser.add_argument("--api-key", default=os.getenv("VERIFY_API_KEY"))
    parser.add_argument("--workers", type=int, default=16)
    parser.add_argument("--limit", type=int)
    args = parser.parse_args()

    sources = {}
    for specification in args.input:
        method, separator, path = specification.partition("=")
        if not separator:
            parser.error("--input must be METHOD=PATH")
        sources[method] = path

    ground_truth = load_json(args.ground_truth)
    records = []
    for method, path in sources.items():
        records.extend(build_patch_records(method, load_json(path)))
    expected_counts = Counter(record["method"] for record in records)
    completed_entries = load_completed(args.output)
    pending_by_bug = group_pending_by_bug(records, completed_entries)
    if args.limit is not None:
        pending_by_bug = dict(list(pending_by_bug.items())[:args.limit])

    write_lock = threading.Lock()
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)

    def append(entry):
        with write_lock:
            with open(args.output, "a", encoding="utf-8") as handle:
                handle.write(json.dumps(entry, ensure_ascii=False) + "\n")
                handle.flush()
                os.fsync(handle.fileno())

    if pending_by_bug:
        if not args.api_key or not args.base_url:
            # Exact matches can still complete without API access.
            has_non_exact_bug = False
            for pending in pending_by_bug.values():
                fix, _ = ground_truth_context(ground_truth, pending[0]["bug_id"])
                if not any(normalize_code(record["patch"]) == normalize_code(fix) for record in pending):
                    has_non_exact_bug = True
                    break
            if has_non_exact_bug:
                raise SystemExit("VERIFY_API_KEY and VERIFY_BASE_URL are required for non-exact patches")
        from openai import OpenAI
        client = OpenAI(api_key=args.api_key, base_url=args.base_url) if args.api_key and args.base_url else None

        def judge_bug(pending):
            fix, annotated = ground_truth_context(ground_truth, pending[0]["bug_id"])
            exact_record = next(
                (record for record in pending if normalize_code(record["patch"]) == normalize_code(fix)),
                None,
            )
            if exact_record is not None:
                entry = dict(exact_record, exact_match=True, judgment="Correct", raw_response="")
                append(entry)
                return

            for record in pending:
                prompt = construct_prompt(annotated, fix, record["patch"])
                try:
                    response = client.chat.completions.create(
                        model=args.model,
                        messages=[{"role": "user", "content": prompt}],
                        temperature=0.0,
                        timeout=180,
                    )
                    raw = response.choices[0].message.content or ""
                    judgment = classify_response(raw)
                    entry = dict(record, exact_match=False, judgment=judgment, raw_response=raw)
                except Exception as error:
                    entry = dict(record, exact_match=False, judgment="Error", error=str(error))
                append(entry)
                if entry["judgment"] == "Correct":
                    return

        with ThreadPoolExecutor(max_workers=max(1, args.workers)) as executor:
            futures = [executor.submit(judge_bug, pending) for pending in pending_by_bug.values()]
            for future in as_completed(futures):
                future.result()

    all_entries = load_completed(args.output)
    summary = summarize_results(all_entries, dict(expected_counts))
    with open(args.summary, "w", encoding="utf-8") as handle:
        json.dump(summary, handle, ensure_ascii=False, indent=2)
    print(json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()
